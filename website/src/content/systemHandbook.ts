// ---------------------------------------------------------------------------
// THE ICOF GLOBAL UNIVERSITY SYSTEM HANDBOOK.
//
// ---------------------------------------------------------------------------
// WHAT THE UNIVERSITY ASKED FOR
// ---------------------------------------------------------------------------
//
// "This will be the master institutional handbook for the entire digital
//  university system. It should serve two purposes simultaneously:
//
//    1. Institutional reference — explains how ICOF Global University operates,
//       including authority, roles, responsibilities, governance, permissions,
//       and workflows.
//    2. System user guide — explains exactly how each member of the university
//       uses the digital system.
//
//  I would therefore structure the handbook around roles and university
//  functions, rather than treating it as merely a software manual."
//
// And the governing principle, in their words:
//
//   "The ICOF Global University System Handbook is the authoritative
//    operational reference for the use of the ICOF Global University digital
//    system. It defines institutional roles, permissions, responsibilities,
//    workflows, controls, and procedures, and provides practical instructions
//    for every authorized user of the system."
//
// ---------------------------------------------------------------------------
// HALF OF THIS FILE IS NOT IN THIS FILE
// ---------------------------------------------------------------------------
//
// "Authoritative" is the word that decides the design. A handbook that states
// in prose what the capability matrix already states in code has stated one
// fact twice, and the second statement is the one that goes wrong: the matrix
// changes, the document does not, and the thing the University calls
// authoritative becomes the least reliable description of the system in the
// building. The National Rector programme map had exactly that fault and was
// accurate for about a day.
//
// So Part II and Part VIII are BUILT, not written. `handbookFromTheSystem.ts`
// is generated by `npm run handbook` from roles.ts, types.ts, portalNav.tsx and
// the migrations, and this file composes its tables into chapters. Every role,
// every capability, every screen an office is served and every rule the
// database has been watched to refuse comes from there.
//
// What is written here is what no schema holds: what the University is, why a
// control exists, how a thing is done, and what to do when it goes wrong.
//
// ---------------------------------------------------------------------------
// AND NO INSTITUTIONAL FACT IS INVENTED
// ---------------------------------------------------------------------------
//
// Not an accreditation, not a campus, not a partnership, not a statistic. The
// facts about the institution come from `constants.ts`; the facts about the
// system come from the system. Where the handbook does not know something, it
// says the office to ask rather than filling the gap.
// ---------------------------------------------------------------------------

