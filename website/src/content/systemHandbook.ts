const p = (text: string): Block => ({ kind: 'p', text });
const lead = (text: string): Block => ({ kind: 'lead', text });
const h = (text: string): Block => ({ kind: 'h', text });
const bullets = (...items: string[]): Block => ({ kind: 'bullets', items });
const defs = (...items: { term: string; text: string }[]): Block => ({ kind: 'defs', items });
const flow = (...steps: string[]): Block => ({ kind: 'flow', steps });

/**
 * A drawn figure.
 *
 * DRAWN WHEN THIS MODULE LOADS, from the same generated data Part II and Part
 * VIII are built from — so a chart of what each office holds cannot
 * disagree with the list of what each office holds three pages earlier. That is
 * the whole reason the figures are code rather than files.
 */
const figure = (title: string, svgMarkup: string, caption?: string): Block =>
  ({ kind: 'figure', title, svg: svgMarkup, caption });

const ch = (ordinal: string, title: string, ...blocks: Block[]): Chapter =>
  ({ ordinal, title, blocks });

/** Sentence case for a capability, so a table reads as English. */
const phrase = (capability: string) => capability.replace(/-/g, ' ');

const profile = (role: string): RoleProfile => {
  const found = ROLE_PROFILES.find((r) => r.role === role);
  if (!found) {
    // A ROLE NAMED HERE AND ABSENT FROM THE SYSTEM IS A HANDBOOK LYING. Better
    // to fail the build than to print a chapter about an office that does not
    // exist, or to quietly omit one that does.
    throw new Error(`systemHandbook: no role "${role}" in the system. Run \`npm run handbook\`.`);
  }
  return found;
};

/**
 * A role's chapter, from the generated profile.
 *
 * THE INTRODUCTION IS WRITTEN AND EVERYTHING ELSE IS READ. What an office is
 * FOR is a judgement about the University; what it may do is a fact about the
 * matrix, and the two are kept visibly apart so that neither can quietly
 * become the other.
 */
function office(ordinal: string, role: string, intro: Block[]): Chapter {
  const r = profile(role);
  const blocks: Block[] = [...intro];

  blocks.push(h('What this office may do'));
  blocks.push(p(
    `${r.label} holds ${r.capabilities.length} of the University’s `
    + `${COUNTS.capabilities} capabilities`
    + (r.rank ? `, and stands ${ordinalWord(r.rank)} in the University’s hierarchy.` : '.'),
  ));
  blocks.push(bullets(...r.capabilities.map(phrase)));

  if (r.withheld.length) {
    blocks.push(h('And what it may not'));
    blocks.push(p(
      'These are held by the offices working immediately beside this one and not by it. '
      + 'They are the separation of duties, and none of them is an oversight.',
    ));
    blocks.push(bullets(...r.withheld.map(phrase)));
  }

  if (r.screens.length) {
    blocks.push(h('What this office is served'));
    blocks.push(p('The sidebar this role signs in to, group by group.'));
    blocks.push(defs(...r.screens.map((g) => ({ term: g.title, text: g.items.join(' · ') }))));
  }

  return { ordinal, title: r.label, blocks };
}

