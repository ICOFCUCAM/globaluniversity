// ---------------------------------------------------------------------------
// The world's coastlines, for the flat map on the credential device.
//
// WHY THIS IS A SEPARATE FILE FROM THE ONE IN credentialArt.
//
// COASTLINES there was written for an orthographic GLOBE turned to 20°E. A
// globe shows one hemisphere and hides the other, so that data stops at the
// limb: Africa, Europe, Arabia, India, Madagascar and the western edge of
// Brazil. Everything else was deliberately absent because it could not have
// been seen.
//
// A flat map has no limb. Every longitude is on the sheet at once, and a world
// map carrying one hemisphere in detail and the other in fragments does not
// read as a world — it reads as a map of somewhere, with vague shapes around
// it. That is what the first attempt looked like, and it is why it is being
// replaced rather than patched.
//
// CLOSED RINGS, so each landmass can be filled as well as stroked. An outline
// alone is a wire drawing; at 100mm across, wire drawings of continents read as
// a tangle of lines and the eye cannot separate land from sea. A very light
// tone inside the ring is what turns lines into a map.
//
// THE RESOLUTION IS DELIBERATE. Roughly 1-3° — enough that the shape a reader
// recognises survives, no more. At the size this prints, a fjord is thinner
// than the ink. What has to be right is the taper of South America, the hook of
// Alaska, the Horn of Africa, the Gulf, the Indian peninsula, the bulge of
// Australia; those are what identify a continent at a glance and everything
// below them is ink for nobody.
//
// TWO HONEST SIMPLIFICATIONS, recorded here so nobody later mistakes them for
// bugs:
//
//   The Baltic is not cut. Eurasia's perimeter runs from Norway across to the
//   Low Countries, so Denmark and the Baltic coast are inside the landmass. At
//   this scale the Baltic is about a millimetre and cutting it in produced a
//   self-intersecting ring that filled wrong.
//
//   Antarctica is absent. The map is cut at 60°S, as the United Nations emblem
//   is, because on an azimuthal equidistant projection centred on the pole the
//   SOUTH pole is not a point but the entire outer rim — Antarctica can only be
//   drawn as a smear round the edge of the disc.
// ---------------------------------------------------------------------------

